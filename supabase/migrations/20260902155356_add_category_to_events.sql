-- 자료의 카테고리를 글에 직접 저장한다.
--
-- 그동안은 첨부가 들어있는 폴더 이름으로 카테고리를 유추했다. 마이그레이션
-- 없이 시작할 수 있어서 그렇게 뒀는데, 실제 자료를 넣어 보니 한 글에 여러
-- 폴더의 파일이 붙는 경우가 흔했다. 그러면 첫 번째 첨부의 폴더 하나로만
-- 잡혀서, 예를 들어 주일학교와 성경공부 파일이 같이 붙은 글은 성경공부로
-- 걸러낼 수 없었다.
--
-- 값은 드라이브의 2단계 폴더 이름(주보, 악보, 회의록 …)과 맞춘다. 다만
-- 폴더가 이름을 바꾸거나 사라져도 글이 끊기지 않도록 외래키로 묶지 않고
-- 부서(department)와 같은 방식으로 텍스트로 둔다.
--
-- 기존 글은 null 로 남는다. 화면은 값이 없으면 예전처럼 첨부 폴더에서
-- 유추해 보여주므로 당장 비어 보이지는 않는다.

alter table events add column category text;

-- 카테고리로 거르는 목록을 위해. 부서 인덱스와 같은 이유다.
create index events_category_idx on events (category);
